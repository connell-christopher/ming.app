-- Tweaklr TikTok integration
-- Run this migration in the Supabase SQL Editor before deploying the Edge Functions.

create table if not exists public.tweak_tiktok_oauth_states (
  state text primary key,
  tweaklr_user_id uuid not null references auth.users(id) on delete cascade,
  redirect_uri text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists tweak_tiktok_oauth_states_expiry_idx
  on public.tweak_tiktok_oauth_states (expires_at);

create table if not exists public.tweak_tiktok_connections (
  tweaklr_user_id uuid primary key references auth.users(id) on delete cascade,
  tiktok_open_id text not null unique,
  display_name text,
  avatar_url text,
  access_token text not null,
  refresh_token text not null,
  scope text,
  access_token_expires_at timestamptz,
  refresh_token_expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tweak_tiktok_videos (
  id bigint generated by default as identity primary key,
  tweaklr_user_id uuid not null references auth.users(id) on delete cascade,
  tiktok_video_id text not null,
  title text,
  video_description text,
  duration integer,
  cover_image_url text,
  embed_link text,
  share_url text,
  create_time bigint,
  fetched_at timestamptz not null default now(),
  unique (tweaklr_user_id, tiktok_video_id)
);

create index if not exists tweak_tiktok_videos_owner_created_idx
  on public.tweak_tiktok_videos (tweaklr_user_id, create_time desc);

alter table public.tweak_tiktok_oauth_states enable row level security;
alter table public.tweak_tiktok_connections enable row level security;
alter table public.tweak_tiktok_videos enable row level security;

-- No client-facing policies are intentionally created. All OAuth state and
-- TikTok tokens are accessed only by trusted Edge Functions using service role.
revoke all on table public.tweak_tiktok_oauth_states from anon, authenticated;
revoke all on table public.tweak_tiktok_connections from anon, authenticated;
revoke all on table public.tweak_tiktok_videos from anon, authenticated;
